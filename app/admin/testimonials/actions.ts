const TESTIMONIALS_BUCKET = 'testimonials';

function toTestimonialPath(value: string | null | undefined): string | null {
  if (!value?.trim()) return null;
  try {
    return getAdminStoragePath(TESTIMONIALS_BUCKET, value);
  } catch {
    return null;
  }
}

/** Parse the paths uploaded by this form. Only UUID-named uploads generated by
 * our server uploader are eligible for automatic cleanup. */
function getUploadedPaths(formData: FormData): string[] {
  const raw = formData.get('uploaded_paths');
  if (typeof raw !== 'string' || raw.length === 0 || raw.length > 20_000) return [];

  try {
    const parsed: unknown = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return [...new Set(
      parsed
        .filter((value): value is string => typeof value === 'string')
        .map((value) => value.trim())
        .filter((value) => value.length > 0 && value.length <= 2_000),
    )].slice(0, 64);
  } catch {
    return [];
  }
}

function getManagedTestimonialPaths(values: readonly string[]): string[] {
  return [...new Set(
    values
      .map((value) => getManagedUploadPath(TESTIMONIALS_BUCKET, value))
      .filter((value): value is string => Boolean(value)),
  )];
}

async function cleanupTestimonialPaths(
  supabase: AuthenticatedServerContext['supabase'],
  values: readonly (string | null | undefined)[],
): Promise<void> {
  const paths = [...new Set(values.map((value) => toTestimonialPath(value)).filter((value): value is string => Boolean(value)))];
  if (paths.length === 0) return;

  try {
    await removeAdminStorageObjects(TESTIMONIALS_BUCKET, paths, supabase);
  } catch {
    // Keep the successful DB mutation visible. Failed cleanup can be retried
    // from the Media section.
  }
}

async function rollbackTestimonialUploads(
  supabase: AuthenticatedServerContext['supabase'],
  values: readonly (string | null | undefined)[],
): Promise<void> {
  const paths = [...new Set(values.map((value) => getManagedUploadPath(TESTIMONIALS_BUCKET, value)).filter((value): value is string => Boolean(value)))];
  if (paths.length === 0) return;

  try {
    await removeAdminStorageObjects(TESTIMONIALS_BUCKET, paths, supabase);
  } catch {
    // Do not mask the original database failure.
  }
}

function testimonialFolder(type: MediaType, testimonialId?: string): string {
  const folder = type === 'avatar' ? 'avatars' : type === 'screenshot' ? 'screenshots' : 'gallery';
  return testimonialId ? `${folder}/${testimonialId}` : folder;
}

export async function uploadTestimonialImageAction(
  file: File,
  type: MediaType,
  testimonialId?: string,
  oldPath?: string | null
): Promise<{ path: string; name: string; size: number; type: string; url: string }> {
  if (testimonialId) assertUuid(testimonialId);
  const result = await uploadAdminImage({
    bucket: TESTIMONIALS_BUCKET,
    folder: testimonialFolder(type, testimonialId),
    file,
    oldPath,
  });
  return { ...result, name: file.name, size: file.size, type: file.type };
}

export async function deleteTestimonialImageAction(path: string): Promise<void> {
  await deleteAdminImage(TESTIMONIALS_BUCKET, path);
}

export async function createTestimonial(formData: FormData) {
  await validateCSRF();
  const { supabase } = await requireAdminServerContext();
  const uploadedPaths = getUploadedPaths(formData);
  let committed = false;
  try {

    const name = requireFormText(formData, 'name', 120);
    const surname = getFormText(formData, 'surname', 120);
    const position = getFormText(formData, 'position', 240);
    const company = getFormText(formData, 'company', 240);
    const location = getFormText(formData, 'location', 240);
    const content = requireFormText(formData, 'content', 10_000);
    const avatar_path = getFormText(formData, 'avatar_path', 2_000);
    const screenshot_path = getFormText(formData, 'screenshot_path', 2_000);
    const source_url = getFormText(formData, 'source_url', 2_000);
    const rating = getBoundedInteger(getFormText(formData, 'rating', 1), 5, 1, 5);
    const published = formData.get('published') === 'true';

    // order_index will be automatically assigned by database sequence
    const { error } = await supabase.from('testimonials').insert({
      name,
      surname: surname || null,
      position: position || null,
      company: company || null,
      location: location || null,
      content,
      avatar_path: avatar_path || null,
      screenshot_path: screenshot_path || null,
      source_url: source_url || null,
      rating,
      published,
    });

    if (error) throw new Error(error.message);
    committed = true;

    const persistedPaths = new Set(
      [avatar_path, screenshot_path]
        .map((value) => toTestimonialPath(value))
        .filter((value): value is string => Boolean(value)),
    );
    await cleanupTestimonialPaths(
      supabase,
      getManagedTestimonialPaths(uploadedPaths).filter((path) => !persistedPaths.has(path)),
    );

    const displayName = surname ? `${name} ${surname}` : name;
    await logActivity({ action: 'create', entityType: 'testimonials', entityName: displayName });

    revalidatePath('/admin/testimonials');
    revalidatePath('/'); // Revalidate public page
    redirect('/admin/testimonials');
  } catch (error: unknown) {
    if (!committed) await rollbackTestimonialUploads(supabase, uploadedPaths);
    throw error;
  }
}

export async function updateTestimonial(id: string, formData: FormData) {
  await validateCSRF();
  assertUuid(id);
  const uploadedPaths = getUploadedPaths(formData);
  const { supabase } = await requireAdminServerContext();
  let committed = false;
  try {

  const name = requireFormText(formData, 'name', 120);
  const surname = getFormText(formData, 'surname', 120);
  const position = getFormText(formData, 'position', 240);
  const company = getFormText(formData, 'company', 240);
  const location = getFormText(formData, 'location', 240);
  const content = requireFormText(formData, 'content', 10_000);
  const avatar_path = getFormText(formData, 'avatar_path', 2_000);
  const screenshot_path = getFormText(formData, 'screenshot_path', 2_000);
  const source_url = getFormText(formData, 'source_url', 2_000);
  const rating = getBoundedInteger(getFormText(formData, 'rating', 1), 5, 1, 5);
  const published = formData.get('published') === 'true';

  // Get existing testimonial to check for deleted images
  const { data: existing, error: existingError } = await supabase
    .from('testimonials')
    .select('avatar_path, screenshot_path')
    .eq('id', id)
    .maybeSingle();

  if (existingError) throw new Error(existingError.message);
  if (!existing) throw new Error('Testimonial was not found');

  const { error, count } = await supabase
    .from('testimonials')
    .update({
      name,
      surname: surname || null,
      position: position || null,
      company: company || null,
      location: location || null,
      content,
      avatar_path: avatar_path || null,
      screenshot_path: screenshot_path || null,
      source_url: source_url || null,
      rating,
      published,
    }, { count: 'exact' })
    .eq('id', id);

  if (error) throw new Error(error.message);
  if (count !== 1) throw new Error('Testimonial was not found or was not updated');
  committed = true;

  const previousPaths = [existing?.avatar_path, existing?.screenshot_path]
    .map((value) => toTestimonialPath(value))
    .filter((value): value is string => Boolean(value));
  const nextPaths = new Set(
    [avatar_path, screenshot_path]
      .map((value) => toTestimonialPath(value))
      .filter((value): value is string => Boolean(value)),
  );
  await cleanupTestimonialPaths(
    supabase,
    [
      ...previousPaths.filter((path) => !nextPaths.has(path)),
      ...getManagedTestimonialPaths(uploadedPaths).filter((path) => !nextPaths.has(path)),
    ],
  );

  const displayName = surname ? `${name} ${surname}` : name;
  await logActivity({ action: 'update', entityType: 'testimonials', entityId: id, entityName: displayName });

  revalidatePath('/admin/testimonials');
  revalidatePath('/'); // Revalidate public page
  redirect('/admin/testimonials');
  } catch (error: unknown) {
    if (!committed) await rollbackTestimonialUploads(supabase, uploadedPaths);
    throw error;
  }
}

export async function deleteTestimonial(id: string) {
  await validateCSRF();
  assertUuid(id);
  const { supabase } = await requireAdminServerContext();

  // Get testimonial to delete associated images
  const { data: testimonial, error: fetchError } = await supabase
    .from('testimonials')
    .select('name, avatar_path, screenshot_path')
    .eq('id', id)
    .maybeSingle();
  if (fetchError) throw new Error(fetchError.message);

  // Delete testimonial from database
  const { error, count } = await supabase
    .from('testimonials')
    .delete({ count: 'exact' })
    .eq('id', id);

  if (error) {
    throw new Error(error.message);
  }
  if (count !== 1 || !testimonial) {
    throw new Error('Testimonial was not found or was not deleted');
  }

  if (testimonial?.avatar_path) {
    await cleanupTestimonialPaths(supabase, [testimonial.avatar_path]);
  }
  if (testimonial?.screenshot_path) {
    await cleanupTestimonialPaths(supabase, [testimonial.screenshot_path]);
  }

  await logActivity({ action: 'delete', entityType: 'testimonials', entityId: id, entityName: testimonial?.name });

  revalidatePath('/admin/testimonials');
  revalidatePath('/'); // Revalidate public page
}

export async function togglePublished(id: string, published: boolean) {
  await validateCSRF();
  assertUuid(id);
  const { supabase } = await requireAdminServerContext();

  const { data: item } = await supabase.from('testimonials').select('name, surname').eq('id', id).single();
  const { error } = await supabase
    .from('testimonials')
    .update({ published })
    .eq('id', id);

  if (error) {
    throw new Error(error.message);
  }

  const displayName = item?.surname ? `${item.name} ${item.surname}` : item?.name;
  await logActivity({ action: published ? 'publish' : 'unpublish', entityType: 'testimonials', entityId: id, entityName: displayName || undefined });

  revalidatePath('/admin/testimonials');
  revalidatePath('/'); // Revalidate public page
}

export async function reorderTestimonials(ids: string[]) {
  await validateCSRF();
  assertUuidList(ids);
  const { supabase } = await requireAdminServerContext();

  // Convert ids array to items with order_index
  const items = ids.map((id, index) => ({ id, order_index: index }));

  // Use optimized batch update
  await batchUpdateOrder(supabase, 'testimonials', items);

  revalidatePath('/admin/testimonials');
  revalidatePath('/'); // Revalidate public page
}
